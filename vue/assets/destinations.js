/** Which sheet codes allow each document. Upload a document is always available. */
export const DOCUMENT_CODES = {coo: ['C', 'E'], eur: ['U'], ata: ['N'], iic: ['G'], arab: ['A'], invoice: ['I'], eurmed: ['M']};

/** Older names the app used before the sheet, mapped to the sheet's names. */
